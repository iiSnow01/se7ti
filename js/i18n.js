function detectLanguage() {
  const stored = localStorage.getItem("se7ti-lang");
  if (stored) return stored;
  const navLang = navigator.language || "fr";
  if (navLang.startsWith("ar")) return "ar";
  if (navLang.startsWith("fr")) return "fr";
  return "dz";
}

function setLanguage(lang) {
  localStorage.setItem("se7ti-lang", lang);
  document.documentElement.setAttribute("data-lang", lang);
  document.documentElement.lang = lang === "dz" ? "fr" : lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

function t(key, lang) {
  const value = Se7tiI18n.strings[key];
  if (!value) return key;
  return value[lang] || value.fr || key;
}
